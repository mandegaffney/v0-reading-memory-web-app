#!/usr/bin/env node
/**
 * postinstall: fix-next-shim.js
 *
 * pnpm generates node_modules/.bin/next as a POSIX shell script.
 * Claude Code's preview tool calls `node node_modules/.bin/next`, which
 * makes Node.js try to parse the shell script as JavaScript — and fail.
 *
 * This script replaces the shell shim with a valid Node.js wrapper that
 * sets NODE_PATH identically and then requires the real Next.js binary.
 * Runs automatically after every `npm install` or `pnpm install`.
 */
'use strict';

const fs   = require('fs');
const path = require('path');

const shimPath  = path.join(__dirname, '..', 'node_modules', '.bin', 'next');
const pnpmStore = path.join(__dirname, '..', 'node_modules', '.pnpm');

// Find the actual next binary inside pnpm's content-addressable store
function findNextBin() {
  if (!fs.existsSync(pnpmStore)) {
    // npm layout — next binary is at node_modules/next/dist/bin/next
    return path.join(__dirname, '..', 'node_modules', 'next', 'dist', 'bin', 'next');
  }

  const entries = fs.readdirSync(pnpmStore);
  const nextDir = entries.find(e => e.startsWith('next@'));
  if (!nextDir) throw new Error('Cannot find next package in pnpm store');

  return path.join(pnpmStore, nextDir, 'node_modules', 'next', 'dist', 'bin', 'next');
}

function buildNodePaths(nextBin) {
  const nextPkg    = path.dirname(path.dirname(path.dirname(nextBin))); // .../next/
  const nextMods   = path.join(nextPkg, 'node_modules');
  const parentMods = path.dirname(nextPkg);                              // .pnpm/<ver>/node_modules/
  const pnpmMods   = path.join(pnpmStore, 'node_modules');

  return [nextMods, parentMods, pnpmMods].filter(fs.existsSync);
}

try {
  if (!fs.existsSync(shimPath)) {
    console.log('[fix-next-shim] node_modules/.bin/next not found — skipping');
    process.exit(0);
  }

  const nextBin   = findNextBin();
  const nodePaths = buildNodePaths(nextBin);

  const shim = `#!/usr/bin/env node
'use strict';
// Auto-generated by scripts/fix-next-shim.js (postinstall).
// Replaces the pnpm shell shim so Claude Code's preview tool can run
// \`node node_modules/.bin/next\` without a shell-script parse error.
const path = require('path');
const extra = ${JSON.stringify(nodePaths, null, 2)};
process.env.NODE_PATH = [...extra, process.env.NODE_PATH || '']
  .filter(Boolean).join(require('path').delimiter);
require('module').Module._initPaths();
require(${JSON.stringify(nextBin)});
`;

  fs.writeFileSync(shimPath, shim, { mode: 0o755 });
  console.log('[fix-next-shim] Patched node_modules/.bin/next ✓');
} catch (err) {
  // Non-fatal — a broken shim is better than a broken install
  console.warn('[fix-next-shim] Warning:', err.message);
}
